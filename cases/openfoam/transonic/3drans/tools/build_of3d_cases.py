"""Generate OpenFOAM 3D RANS cases (rhoSimpleFoam + SpalartAllmaras).

Geometry: STLs generated by gen_stl.py (same generators as the TSD side).
Half-model: symmetry plane at y=0, wing root cap lies below the plane.
M6   : M=0.84 alpha=3.06 Re_root=14.6e6, TMR CFD convention
       (ref area 1.15315084119231, MAC 0.801672958512342, semispan 1.47601797621980).
Probes: rae2822/naca0012 at M=0.85 alpha=1.25, dfvlr_r4 at M=0.925 alpha=1.25
       (published_refs.json keys), Re_root=14.6e6, aref=0.8, lref=1, cofr (0.25 0 0).

Mesh: blockMesh background + snappyHexMesh (castellated+snap+prism layers),
      first layer 2e-6 (y+<=1 at Re 14.6e6), expansion 1.2, 46 surface layers.

Run: python tools/build_of3d_cases.py <outdir>   (writes case dirs)
"""
import math
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from case_params import GEO, LEVELS, freestream, GAMMA, R, TINF, RE_ROOT  # noqa

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'cases')
FOAM = 'FoamFile { version 2.0; format ascii;'


def box_for(geo):
    if geo == 'm6wing':
        return ((-12, 0, -20), (40, 30, 20)), (64, 24, 48)
    return ((-12, 0, -20), (40, 20, 20)), (64, 20, 48)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(text)


def blockmesh(geo):
    (mn, mx), (nx, ny, nz) = box_for(geo)
    x0, y0, z0 = mn
    x1, y1, z1 = mx
    v = [x0, y0, z0, x1, y1, z1]
    return f"""{FOAM} class dictionary; object blockMeshDict; }}
convertToMeters 1;
vertices (
 ({v[0]} {v[1]} {v[2]}) ({v[3]} {v[1]} {v[2]}) ({v[3]} {v[4]} {v[2]}) ({v[0]} {v[4]} {v[2]})
 ({v[0]} {v[1]} {v[5]}) ({v[3]} {v[1]} {v[5]}) ({v[3]} {v[4]} {v[5]}) ({v[0]} {v[4]} {v[5]}));
blocks (hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1));
edges ();
boundary (
  farfield {{ type patch; faces ((0 4 7 3) (1 2 6 5) (0 3 2 1) (4 5 6 7) (3 2 6 7)); }}
  rootSym {{ type symmetry; faces ((0 1 5 4)); }});
mergePatchPairs ();
"""


def snappy(geo, stl, lv):
    p = LEVELS[lv]
    if geo == 'm6wing':
        reg = f"""
 refinementRegions {{
  m6wing.stl {{ mode distance; levels ((0.2 {p['reg']}) (0.6 {p['reg'] - 1})); }} }}"""
    else:
        reg = f"""
 refinementRegions {{
  {stl} {{ mode distance; levels ((0.2 {p['reg']}) (0.6 {p['reg'] - 1})); }} }}"""
    return f"""{FOAM} class dictionary; object snappyHexMeshDict; }}
castellatedMesh true; snap true; addLayers true;
geometry {{ {stl} {{ type triSurfaceMesh; file "{stl}"; }} }}
castellatedMeshControls {{
 maxLocalCells {p['maxgc']}; maxGlobalCells {p['maxgc']}; minRefinementCells 10;
 maxLoadUnbalance 0.1; nCellsBetweenLevels 3;
 features ();
 refinementSurfaces {{ {stl} {{ level ({p['sur'][0]} {p['sur'][1]}); patchInfo {{ type wall; }} }} }}
 resolveFeatureAngle 25;{reg}
  locationInMesh (0.0 10.0 0.0);
 allowFreeStandingZoneFaces true;
}}
snapControls {{ nSmoothPatch 3; tolerance 2.0; nSolveIter 30; nRelaxIter 5; }}
addLayersControls {{
 relativeSizes false;
 layers {{ "{stl}" {{ nSurfaceLayers {p['layers']}; }} }}
 expansionRatio 1.2; finalLayerThickness {p['first']}; minThickness 1e-7;
 nGrow 0; featureAngle 60; slipFeatureAngle 30; nRelaxIter 5;
 nSmoothSurfaceNormals 1; nSmoothNormals 3; nSmoothThickness 10;
 maxFaceThicknessRatio 0.5; maxThicknessToMedialRatio 0.3;
 minMedianAxisAngle 90; minMedialAxisAngle 90; nBufferCellsNoExtrude 0;
 nLayerIter 50; }}
meshQualityControls {{ #include "meshQualityDict" nSmoothScale 4; errorReduction 0.75; }}
writeFlags (scalarLevels layerSets);
mergeTolerance 1e-6;
"""


def fvschemes():
    return f"""{FOAM} class dictionary; object fvSchemes; }}
ddtSchemes {{ default steadyState; }}
gradSchemes {{ default Gauss linear; grad(p) Gauss linear; }}
divSchemes {{
 default none;
 div(phi,U) Gauss linearUpwind grad(U);
 div(phi,T) Gauss upwind;
 div(phi,nuTilda) Gauss upwind;
 div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear corrected; }}
interpolationSchemes {{ default linear; }}
snGradSchemes {{ default corrected; }}
fluxRequired {{ default no; p; }}
"""


def fvsolution():
    return f"""{FOAM} class dictionary; object fvSolution; }}
solvers
{{
 p {{ solver GAMG; tolerance 1e-7; relTol 0.01; smoother DICGaussSeidel;
     nCellsInCoarsestLevel 1000; }}
 U {{ solver smoothSolver; smoother GaussSeidel; nSweeps 2;
     tolerance 1e-8; relTol 0.01; }}
 T {{ solver smoothSolver; smoother GaussSeidel; nSweeps 2;
     tolerance 1e-8; relTol 0.01; }}
 nuTilda {{ solver smoothSolver; smoother GaussSeidel; nSweeps 2;
     tolerance 1e-8; relTol 0.01; }}
}}
rhoSimple {{ momentumPredictor yes; nNonOrthogonalCorrectors 0; consistent no;
    rhoMin 0.01; rhoMax 5; }}
relaxationFactors {{
 fields {{ p 0.3; rho 0.3; }}
 equations {{ U 0.7; nuTilda 0.7; }}
}}
"""


def control(geo, stl, lv, M, alpha):
    fs = freestream(M)
    U = fs['U']
    a = math.radians(alpha)
    Ux, Uz = U * math.cos(a), U * math.sin(a)
    g = GEO[geo]
    return f"""{FOAM} class dictionary; object controlDict; }}
application rhoSimpleFoam;
startFrom startTime; startTime 0; stopAt endTime; endTime 12000;
deltaT 1; writeControl timeStep; writeInterval 3000; purgeWrite 0;
writeFormat ascii; writePrecision 8; writeCompression uncompressed;
timeFormat general; timePrecision 8;
functions
{{
 forces1
 {{
  type forceCoeffs; libs ("libforces.so"); writeControl timeStep; writeInterval 5;
  patches ("{stl}"); rhoInf {fs['rho']}; magUInf {U};
  lRef {g['lref']}; rhoRef {fs['rho']};
  CofR ({g['cofr'][0]} {g['cofr'][1]} {g['cofr'][2]});
  dragDir (1 0 0); liftDir (0 0 1); pitchAxis (0 1 0);
  Aref {g['aref']};
 }}
 residuals1
 {{
  type residuals; libs ("libutilityFunctionObjects.so");
  writeControl timeStep; writeInterval 5; fields (U p nuTilda);
 }}
}}
"""


def field_p(geo, M):
    fs = freestream(M)
    return f"""{FOAM} class volScalarField; object p; }}
dimensions [1 -1 -2 0 0 0 0];
internalField uniform {fs['p']};
boundaryField {{
 farfield {{ type freestreamPressure; freestreamValue uniform {fs['p']}; }}
  rootSym {{ type symmetry; }}
 "{stl_patch(geo)}" {{ type zeroGradient; }}
}}
"""


def field_u(geo, M, alpha):
    fs = freestream(M)
    a = math.radians(alpha)
    Ux, Uz = fs['U'] * math.cos(a), fs['U'] * math.sin(a)
    return f"""{FOAM} class volVectorField; object U; }}
dimensions [0 1 -1 0 0 0 0];
internalField uniform ({Ux} 0 {Uz});
boundaryField {{
 farfield {{ type freestream; freestreamValue uniform ({Ux} 0 {Uz}); }}
  rootSym {{ type symmetry; }}
 "{stl_patch(geo)}" {{ type fixedValue; value uniform (0 0 0); }}
}}
"""


def field_t(geo, M):
    return f"""{FOAM} class volScalarField; object T; }}
dimensions [0 0 0 1 0 0 0];
internalField uniform {TINF};
boundaryField {{
 farfield {{ type freestream; freestreamValue uniform {TINF}; }}
  rootSym {{ type symmetry; }}
 "{stl_patch(geo)}" {{ type zeroGradient; }}
}}
"""


def field_nutilda(geo, M):
    fs = freestream(M)
    nu = fs['mu'] / fs['rho']
    v = 3.0 * nu
    return f"""{FOAM} class volScalarField; object nuTilda; }}
dimensions [0 2 -1 0 0 0 0];
internalField uniform {v};
boundaryField {{
 farfield {{ type inletOutlet; inletValue uniform {v}; value uniform {v}; }}
  rootSym {{ type symmetry; }}
  "{stl_patch(geo)}" {{ type fixedValue; value uniform 0; }}
}}
"""


def field_nut(geo, M):
    fs = freestream(M)
    nu = fs['mu'] / fs['rho']
    v = 3.0 * nu
    return f"""{FOAM} class volScalarField; object nut; }}
dimensions [0 2 -1 0 0 0 0];
internalField uniform {v};
boundaryField {{
 farfield {{ type inletOutlet; inletValue uniform {v}; value uniform {v}; }}
 symm {{ type symmetry; }}
  "{stl_patch(geo)}" {{ type nutkWallFunction; value uniform 0; }}
}}
"""


def thermo():
    return f"""{FOAM} class dictionary; object thermophysicalProperties; }}
thermoType
{{
 type hePsiThermo; mixture pureMixture; transport sutherland;
 thermo janaf; equationOfState perfectGas; specie specie;
 energy sensibleInternalEnergy;
}}
mixture
{{
 specie {{ molWeight 28.96; }}
 thermodynamics
 {{
  Tlow 100; Thigh 10000; Tcommon 1000;
  highCpCoeffs
  (
   2.9525407 0.0013968838 -4.9262577e-07 7.8600091e-11 -4.6074978e-15
   -923.93753 5.8718221
  );
  lowCpCoeffs
  (
   3.5309628 -0.0001236595 -5.0299339e-07 2.4352768e-09 -1.4087954e-12
   -1046.9637 2.9674391
  );
 }}
 transport {{ As 1.458e-06; Ts 110.4; Pr 0.72; }}
}}
"""


def turb():
    return f"""{FOAM} class dictionary; object turbulenceProperties; }}
simulationType RAS;
RAS {{
 RASModel SpalartAllmaras;
 turbulence on;
 printCoeffs on;
 Cb1 0.1355; Cb2 0.622; Cv1 7.1; Cs 0.3; kappa 0.41; Cw2 0.3;
 Cw3 2.0; sigmaNut 0.66666; sigmaNuTilda 0.66666; Prt 0.9;
}}
"""


def meshquality():
    return f"""{FOAM} class dictionary; object meshQualityDict; }}
maxNonOrtho 70;
maxBoundaryNonOrtho 75;
maxInternalSkewness 4;
maxBoundarySkewness 20;
maxConcave 80;
minVol 1e-13;
minTetQuality 1e-30;
minArea -1;
minDeterminant 0.001;
minFaceWeight 0.05;
minVolRatio 0.01;
minTriangleTwist -1;
nSmoothScale 4;
errorReduction 0.75;
"""


def stl_patch(geo):
    return GEO[geo]['stl'].replace('.stl', '.stl')


CASES = [
    ('m6_coarse', 'm6wing', 'm6wing.stl', 0.84, 3.06, 'coarse'),
    ('m6_medium', 'm6wing', 'm6wing.stl', 0.84, 3.06, 'medium'),
    ('m6_fine', 'm6wing', 'm6wing.stl', 0.84, 3.06, 'fine'),
    ('rae2822_coarse', 'rae2822', 'rae2822.stl', 0.85, 1.25, 'coarse'),
    ('rae2822_medium', 'rae2822', 'rae2822.stl', 0.85, 1.25, 'medium'),
    ('naca0012_coarse', 'naca0012', 'naca0012.stl', 0.85, 1.25, 'coarse'),
    ('naca0012_medium', 'naca0012', 'naca0012.stl', 0.85, 1.25, 'medium'),
    ('dfvlr_r4_coarse', 'dfvlr_r4', 'dfvlr_r4.stl', 0.925, 1.25, 'coarse'),
    ('dfvlr_r4_medium', 'dfvlr_r4', 'dfvlr_r4.stl', 0.925, 1.25, 'medium'),
]


def main():
    selected = [c for c in CASES if len(sys.argv) < 3 or c[0] in sys.argv[2:]]
    for name, geo, stl, M, alpha, lv in selected:
        d = os.path.join(OUT, name)
        stl_dest = os.path.join(d, 'constant', 'triSurface', stl)
        os.makedirs(os.path.dirname(stl_dest), exist_ok=True)
        shutil.copy2(os.path.join(HERE, '..', 'stl', stl), stl_dest)
        write(os.path.join(d, 'system', 'blockMeshDict'), blockmesh(geo))
        write(os.path.join(d, 'system', 'snappyHexMeshDict'), snappy(geo, stl, lv))
        write(os.path.join(d, 'system', 'fvSchemes'), fvschemes())
        write(os.path.join(d, 'system', 'fvSolution'), fvsolution())
        write(os.path.join(d, 'system', 'meshQualityDict'), meshquality())
        write(os.path.join(d, 'system', 'controlDict'), control(geo, stl, lv, M, alpha))
        write(os.path.join(d, 'constant', 'thermophysicalProperties'), thermo())
        write(os.path.join(d, 'constant', 'turbulenceProperties'), turb())
        write(os.path.join(d, '0', 'p'), field_p(geo, M))
        write(os.path.join(d, '0', 'U'), field_u(geo, M, alpha))
        write(os.path.join(d, '0', 'T'), field_t(geo, M))
        write(os.path.join(d, '0', 'nuTilda'), field_nutilda(geo, M))
        write(os.path.join(d, '0', 'nut'), field_nut(geo, M))
        fs = freestream(M)
        print(f'{name:18s} M={M:.3f} alpha={alpha} U=({fs["U"]*math.cos(math.radians(alpha)):.4f} 0 '
              f'{fs["U"]*math.sin(math.radians(alpha)):.4f}) p={fs["p"]:.1f} rho={fs["rho"]:.5f} nu={fs["nu"]:.2e}')
    print(f'wrote {len(selected)} cases to {OUT}')


if __name__ == '__main__':
    main()
